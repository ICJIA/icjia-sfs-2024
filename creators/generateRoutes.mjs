/**
 * Route generation script for the ICJIA Safe From the Start application.
 *
 * This build-time script consolidates all application routes from various sources
 * (pages, news articles, etc.) into a single appRoutes.json file. This file is used
 * by Nuxt's static site generation to pre-render all pages during the build process.
 *
 * The script is executed as part of the build pipeline via the "scripts" command in package.json.
 *
 * @module creators/generateRoutes
 */

import { createRequire } from "module";
import * as dotenv from "dotenv";

// Create CommonJS require function for use in ES modules
// This allows importing JSON files and CommonJS modules in an ES module context
const require = createRequire(import.meta.url);

const { v4: uuidv4 } = require("uuid");
const jsonfile = require("jsonfile");

// Import the list of page routes generated by pages.js
const pageRoutes = require("../src/json/pages.json");

// News routes are currently disabled but can be re-enabled by uncommenting
// const newsRoutes = require("../src/json/news.json");

// Load environment variables from .env file
dotenv.config();

/**
 * Consolidate all route sources and remove duplicates.
 * Currently only includes page routes, but can be extended to include news routes.
 * The Set ensures no duplicate routes exist in the final array.
 */
const appRoutes = Array.from(new Set([...pageRoutes]));

// Add the homepage route explicitly
// This ensures the root path is always included in static generation
appRoutes.push("/");

/**
 * Write the consolidated routes to appRoutes.json.
 * This file is consumed by nuxt.config.js for the generate.routes configuration,
 * ensuring all routes are pre-rendered during static site generation.
 */
jsonfile.writeFileSync(`./src/json/appRoutes.json`, appRoutes, function (err) {
  if (err) {
    console.error(err);
  }
});

// Log the generated routes for verification during build
console.log("appRoutes.json created in /src/appRoutes.json:", appRoutes);

// Log the total count for build monitoring
console.log("Total app routes: ", appRoutes.length);
